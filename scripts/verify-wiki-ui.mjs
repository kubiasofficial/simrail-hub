import {chromium} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.connectOverCDP('http://127.0.0.1:9222');
const page=browser.contexts()[0].pages()[0];const errors=[];page.on('pageerror',e=>errors.push(e.message));
const capture=path=>process.argv.includes('--no-screenshots')?Promise.resolve():page.screenshot({path});
await page.waitForFunction(()=>!!window.simrailHub);await page.setViewportSize({width:1440,height:1000});
await page.getByRole('button',{name:'Domů',exact:true}).click();
await capture('docs/verification/wiki-home.png');
await page.getByRole('button',{name:'Živá mapa',exact:true}).click();await page.waitForSelector('.station-symbol');
await page.getByLabel('Vyhledat vlak nebo stanici').fill('Katowice');
await page.locator('.search-results').getByRole('button',{name:'Katowice',exact:true}).click();
await page.waitForFunction(()=>{const img=document.querySelector('.station-photo');return img?.complete&&img.naturalWidth>0;});
const station=await page.locator('.station-photo').evaluate(img=>({src:img.src,width:img.naturalWidth}));
await capture('docs/verification/wiki-station.png');
await page.locator('.detail-close').click();
const number=await page.evaluate(async()=>{const r=await window.simrailHub.call('trains:list','cz1');return r.data.trains.find(t=>t.vehicles?.some(v=>v.startsWith('EN57/')||v.startsWith('4E/')))?.number;});
if(!number)throw Error('No matching live vehicle');
await page.getByLabel('Vyhledat vlak nebo stanici').fill(number);await page.locator('.search-results').getByRole('button',{name:'Vlak '+number,exact:true}).click();
await page.waitForFunction(()=>{const img=document.querySelector('.vehicle-card>img');return img?.complete&&img.naturalWidth>0;});
const vehicle=await page.locator('.vehicle-card>img').evaluate(img=>({src:img.src,width:img.naturalWidth,alt:img.alt}));
await page.locator('.map-detail').getByRole('button',{name:'Palubní počítač',exact:true}).click();await page.waitForSelector('.journey-overview');
await page.waitForFunction(()=>{const img=document.querySelector('.vehicle-card>img');return img?.complete&&img.naturalWidth>0;});
await capture('docs/verification/wiki-dashboard.png');
const result={station,vehicle,errors};console.log(result);await writeFile('docs/verification/wiki-ui-results.json',JSON.stringify(result,null,2));await browser.close();
if(errors.length)process.exitCode=1;
