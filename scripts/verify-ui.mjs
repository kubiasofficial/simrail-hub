import { chromium } from '@playwright/test';
import { mkdir,writeFile } from 'node:fs/promises';
await mkdir('docs/verification',{recursive:true});
const browser=await chromium.connectOverCDP('http://127.0.0.1:9222');
const page=browser.contexts()[0].pages()[0]; const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.waitForFunction(()=>!!window.simrailHub);
await page.getByRole('button',{name:'Domů',exact:true}).click();
await page.setViewportSize({width:1440,height:1000});
await page.screenshot({path:'docs/verification/home.png'});
const live=await page.evaluate(async()=>{const api=window.simrailHub;const servers=await api.getServers();const stations=await api.call('stations:list','cz1');const trains=await api.call('trains:list','cz1');return {servers:servers.ok,stations:stations.ok?stations.data.length:stations.error,trains:trains.ok?trains.data.trains.length:trains.error,train:trains.ok?trains.data.trains[0]?.number:null};});
console.log('live counts',live);
await page.getByRole('button',{name:'Živá mapa',exact:true}).click();
await page.waitForSelector('.station-symbol',{timeout:45000});
console.log('map stations',await page.locator('.station-symbol').count(),'train groups',await page.locator('.rail-train,.train-cluster').count());
await page.getByLabel('Vzhled mapy').selectOption('light');await page.getByLabel('Vzhled mapy').selectOption('osm-dark');
await page.getByLabel('Vyhledat vlak nebo stanici').fill('Katowice');await page.locator('.search-results button').first().click();await page.waitForTimeout(700);
await page.screenshot({path:'docs/verification/map.png'});
await page.locator('.detail-close').click();
await page.getByLabel('Vyhledat vlak nebo stanici').fill(live.train);await page.locator('.search-results button').first().click();
await page.locator('.map-detail').getByRole('button',{name:'Palubní počítač',exact:true}).click();await page.waitForSelector('.journey-overview',{timeout:60000});
await page.screenshot({path:'docs/verification/dashboard.png'});
await page.getByRole('button',{name:'Otevřít na mobilu'}).click();await page.waitForSelector('.pairing-qr',{timeout:15000});console.log('QR image',await page.locator('.pairing-qr').getAttribute('src').then(x=>x?.startsWith('data:image/png')));
const pairing=await page.evaluate(async(no)=>window.simrailHub.call('mobile:start','cz1',no),live.train);
if(!pairing.ok)throw Error(pairing.error);
await writeFile('.mobile-test-url',pairing.data.urls[0]);
await page.getByRole('dialog').getByLabel('Zavřít',{exact:true}).click();
await page.getByRole('button',{name:'Nastavení',exact:true}).click();await page.screenshot({path:'docs/verification/settings.png'});
await writeFile('docs/verification/ui-results.json',JSON.stringify({live,errors,qr:true},null,2));
console.log('UI errors',errors);await browser.close();
